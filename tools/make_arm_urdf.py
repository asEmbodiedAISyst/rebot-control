"""Generate the arm-only URDF shipped in ``src/rebot_control/assets/b601_rs/``.

Source: ``ReBot_Arm_RS.urdf`` from Seeed-Projects/reBot-DevArm (``Rebot_Arm_description/RS/``, CERN-OHL-W-2.0).
Changes made here:

* the stock gripper (``gripper_end``, ``gripper_left``, ``gripper_right`` and their joints) is removed; an end
  effector is described by a tool YAML (TCP + payload) instead, the stock gripper included
  (``configs/tools/stock_gripper.yaml``);
* ``<visual>`` / ``<collision>`` elements are removed so the file has no mesh dependencies (kinematics and
  inertial parameters only).

Usage: ``python tools/make_arm_urdf.py <upstream ReBot_Arm_RS.urdf> <output .urdf>``
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET

GRIPPER_LINKS = {"gripper_end", "gripper_left", "gripper_right"}


def main(src: str, dst: str) -> None:
    tree = ET.parse(src)
    root = tree.getroot()
    for link in list(root.findall("link")):
        if link.get("name") in GRIPPER_LINKS:
            root.remove(link)
            continue
        for tag in ("visual", "collision"):
            for el in list(link.findall(tag)):
                link.remove(el)
    for joint in list(root.findall("joint")):
        if joint.find("child").get("link") in GRIPPER_LINKS:
            root.remove(joint)
    for mat in list(root.findall("material")):
        root.remove(mat)
    root.set("name", "rebot_b601_rs_arm")
    ET.indent(tree, space="  ")
    header = ("<?xml version=\"1.0\"?>\n<!-- Generated by tools/make_arm_urdf.py from Seeed-Projects/reBot-DevArm "
              "Rebot_Arm_description/RS/ReBot_Arm_RS.urdf (CERN-OHL-W-2.0): gripper, visual and collision elements "
              "removed. Do not edit by hand. -->\n")
    with open(dst, "w") as f:
        f.write(header + ET.tostring(root, encoding="unicode") + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
